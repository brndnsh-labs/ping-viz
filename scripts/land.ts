// Rasterise Natural Earth land polygons (public domain) into an equirectangular land mask, run-length
// encode it, and write src/geo/land-data.ts. The globe places its dots from this mask.
//
//   curl -sSL -o tmp/data/naturalearth/ne_50m_land.geojson \
//     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
//   npm run land -- tmp/data/naturalearth/ne_50m_land.geojson
import { readFileSync, writeFileSync } from "node:fs";

const W = 1440;
const H = 720;

type Ring = [number, number][];
interface Geometry {
  type: "Polygon" | "MultiPolygon";
  coordinates: Ring[] | Ring[][];
}

const path = process.argv[2];
if (!path) {
  console.error("usage: npm run land -- <ne_50m_land.geojson>");
  process.exit(1);
}
const geo = JSON.parse(readFileSync(path, "utf8")) as { features: { geometry: Geometry }[] };

// Collect every ring's edges once, in pixel space.
const edges: [number, number, number, number][] = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = (g.type === "Polygon" ? [g.coordinates] : g.coordinates) as Ring[][];
  for (const poly of polys) {
    for (const ring of poly) {
      for (let i = 0; i < ring.length; i++) {
        const a = ring[i] as [number, number];
        const b = ring[(i + 1) % ring.length] as [number, number];
        const ax = ((a[0] + 180) / 360) * W;
        const ay = ((90 - a[1]) / 180) * H;
        const bx = ((b[0] + 180) / 360) * W;
        const by = ((90 - b[1]) / 180) * H;
        if (ay !== by) edges.push([ax, ay, bx, by]);
      }
    }
  }
}

// Even-odd scanline fill at each row's pixel centre (holes such as lakes come out right).
const mask = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
  const yc = y + 0.5;
  const xs: number[] = [];
  for (const [ax, ay, bx, by] of edges) {
    if ((ay <= yc && by > yc) || (by <= yc && ay > yc)) xs.push(ax + ((yc - ay) / (by - ay)) * (bx - ax));
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const x0 = Math.max(0, Math.ceil((xs[k] as number) - 0.5));
    const x1 = Math.min(W - 1, Math.floor((xs[k + 1] as number) - 0.5));
    for (let x = x0; x <= x1; x++) mask[y * W + x] = 1;
  }
}

// Runs per row, alternating water/land starting with water (a row that starts on land opens with a
// zero-length water run), as unsigned LEB128 varints. A decoder reads runs until the row is full.
const bytes: number[] = [];
const varint = (v: number): void => {
  let x = v;
  while (x >= 0x80) {
    bytes.push((x & 0x7f) | 0x80);
    x >>>= 7;
  }
  bytes.push(x);
};
let land = 0;
for (let y = 0; y < H; y++) {
  let cur = 0;
  let run = 0;
  for (let x = 0; x < W; x++) {
    const v = mask[y * W + x] as number;
    land += v;
    if (v === cur) run++;
    else {
      varint(run);
      cur = v;
      run = 1;
    }
  }
  varint(run);
}
const b64 = Buffer.from(bytes).toString("base64");
const out = `// Generated by scripts/land.ts from Natural Earth 1:50m land (public domain). Do not edit.
// Equirectangular ${W}x${H} land mask; each row is alternating water/land run lengths (LEB128).
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_RLE =
  "${b64}";
`;
writeFileSync("src/geo/land-data.ts", out);
console.log(`land: ${((land / (W * H)) * 100).toFixed(1)}% of pixels, ${bytes.length} bytes RLE, ${b64.length} base64`);
